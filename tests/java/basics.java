public class Main {
    static int counter = 0;
    static int square(int x) { return x * x; }
    static double avg(int[] a) { int s = 0; for (int x : a) s += x; return (double) s / a.length; }
    public static void main(String[] args) {
        int a = 7, b = 2;
        System.out.println(a / b);
        System.out.println(a % b);
        System.out.println(-7 / 2);
        System.out.println(-7 % 2);
        System.out.println(a / 2.0);
        System.out.println(1.0 / 3);
        System.out.println(0.1 + 0.2);
        System.out.println(100.0);
        System.out.println(1e10);
        System.out.println(1.0e-5);
        System.out.println(12345678.9);
        System.out.println((int) 3.99);
        System.out.println((int) -3.99);
        System.out.println((char) ('a' + 2));
        System.out.println('a' + 2);
        System.out.println('a' + 'b');
        System.out.println("" + 'a' + 'b');
        System.out.println(1 + 2 + "3" + 4 + 5);
        System.out.println(Integer.MAX_VALUE + 1);
        System.out.println(Integer.MIN_VALUE - 1);
        long big = Integer.MAX_VALUE + 1L;
        System.out.println(big);
        System.out.println(2147483647 * 2);
        System.out.println(46341 * 46341);
        int i = 5;
        int j = i++ + ++i;
        System.out.println(i + " " + j);
        int k = 10;
        k += 3.7;
        System.out.println(k);
        char c = 'x';
        c++;
        System.out.println(c);
        c += 1;
        System.out.println(c);
        System.out.println(square(9));
        System.out.println(avg(new int[]{1, 2, 3, 4}));
        boolean t = true, f = false;
        System.out.println(t && !f || f);
        System.out.println(t ^ f);
        System.out.println(5 & 3);
        System.out.println(5 | 3);
        System.out.println(5 ^ 3);
        System.out.println(~5);
        System.out.println(1 << 10);
        System.out.println(-16 >> 2);
        System.out.println(-16 >>> 28);
        System.out.println(-1 >>> 0);
        System.out.println(10 == 10.0);
        System.out.println('A' == 65);
        double d = 10;
        System.out.println(d);
        float fl = 2.5f;
        System.out.println(fl * 2);
        System.out.println(Math.max(3, 7) + Math.min(-1, 4));
        System.out.println(Math.abs(-4.5));
        System.out.println(Math.pow(2, 10));
        System.out.println(Math.sqrt(16));
        System.out.println(Math.round(2.5));
        System.out.println(Math.round(-2.5));
        System.out.println(Math.floor(-1.1));
        System.out.println(Math.ceil(1.1));
        System.out.println(counter++ + counter);
        System.out.println(10 / 3 * 3);
        System.out.println(10 * 3 / 3);
        int x = 0;
        x = x++;
        System.out.println(x);
        System.out.println(07 + 0x1F + 0b101);
        System.out.println(1_000_000);
        System.out.println((byte) 200);
        System.out.println((short) 70000);
        System.out.println((long) 1e19);
        System.out.println((int) Double.NaN);
        System.out.println(5 / 2 + 5 / 2.0);
        var v = 3.0f;
        System.out.println(v);
        System.out.println(Long.MAX_VALUE);
        System.out.println(Long.MIN_VALUE + " " + Integer.MIN_VALUE);
        System.out.println(Double.MAX_VALUE);
        System.out.println(1.0 / 0);
        System.out.println(0.0 / 0);
        System.out.println(-0.0);
        System.out.println(3 > 2 ? "yes" : "no");
        System.out.println(true ? 1 : 2.0);
    }
}
